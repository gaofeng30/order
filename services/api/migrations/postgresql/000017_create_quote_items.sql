CREATE TABLE quote_items (
  quote_id NUMERIC(20,0) CHECK (quote_id BETWEEN 0 AND 18446744073709551615) NOT NULL,
  line_number INTEGER CHECK (line_number BETWEEN 0 AND 65535) NOT NULL,
  product_id NUMERIC(20,0) CHECK (product_id BETWEEN 0 AND 18446744073709551615) NOT NULL,
  product_name_snapshot TEXT NOT NULL,
  product_source_version BYTEA CHECK (octet_length(product_source_version) = 32) NOT NULL,
  image_object_key_snapshot BYTEA CHECK (octet_length(image_object_key_snapshot) <= 1024) NULL,
  original_unit_price_cents NUMERIC(20,0) CHECK (original_unit_price_cents BETWEEN 0 AND 18446744073709551615) NOT NULL,
  discounted_unit_price_cents NUMERIC(20,0) CHECK (discounted_unit_price_cents BETWEEN 0 AND 18446744073709551615) NOT NULL,
  quantity NUMERIC(20,0) CHECK (quantity BETWEEN 0 AND 18446744073709551615) NOT NULL,
  original_subtotal_cents NUMERIC(20,0) CHECK (original_subtotal_cents BETWEEN 0 AND 18446744073709551615) NOT NULL,
  payable_subtotal_cents NUMERIC(20,0) CHECK (payable_subtotal_cents BETWEEN 0 AND 18446744073709551615) NOT NULL,
  flavors_json JSONB NOT NULL,
  line_note TEXT NOT NULL,
  PRIMARY KEY (quote_id, line_number),
  CONSTRAINT fk_quote_items_quote FOREIGN KEY (quote_id) REFERENCES quotes (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  CONSTRAINT chk_quote_items_line_number CHECK (line_number > 0),
  CONSTRAINT chk_quote_items_product_name CHECK (CHAR_LENGTH(TRIM(product_name_snapshot)) > 0),
  CONSTRAINT chk_quote_items_image_key CHECK (image_object_key_snapshot IS NULL OR OCTET_LENGTH(image_object_key_snapshot) BETWEEN 1 AND 1024),
  CONSTRAINT chk_quote_items_prices CHECK (discounted_unit_price_cents <= original_unit_price_cents),
  CONSTRAINT chk_quote_items_quantity CHECK (quantity > 0),
  CONSTRAINT chk_quote_items_original_subtotal CHECK (original_subtotal_cents = original_unit_price_cents * quantity),
  CONSTRAINT chk_quote_items_payable_subtotal CHECK (payable_subtotal_cents = discounted_unit_price_cents * quantity),
  CONSTRAINT chk_quote_items_flavors CHECK (jsonb_typeof(flavors_json)='array')
);
