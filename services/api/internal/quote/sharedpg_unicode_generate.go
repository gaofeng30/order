const normalizationTestSHA = "fb9ac8cc154a80cad6caac9897af55a4e75176af6f4e2bb6edc2bf8b1d57f326"

func main() {
	if len(os.Args) != 3 {
		panic("expected external output directory and Unicode 15 NormalizationTest file")
	}
	assertAuthority()
	recomposition, authority := readRecomposition()
	out, err := filepath.Abs(os.Args[1])
	must(err)
	_, source, _, ok := runtime.Caller(0)
	if !ok {
		panic("generator source location unavailable")
	}
	sourceBytes, err := os.ReadFile(source)
	must(err)
	repo := filepath.Clean(filepath.Join(filepath.Dir(source), "../../../.."))
	rel, err := filepath.Rel(repo, out)
	must(err)
	if rel != ".." && !strings.HasPrefix(rel, ".."+string(filepath.Separator)) {
		panic("output must be outside the repository")
	}
	normalizationTest, err := os.ReadFile(os.Args[2])
	must(err)
	if digest(normalizationTest) != normalizationTestSHA {
		panic("NormalizationTest-15.0.0.txt authority hash mismatch")
	}
	must(os.MkdirAll(out, 0700))

	nfc, nfkc := map[string]int{}, map[string]int{}
	nfcProperties, nfkcProperties := map[string]any{}, map[string]any{}
	var widthSource, widthTarget, spaces strings.Builder
	scalars := 0
	for r := rune(0); r <= unicode.MaxRune; r++ {
		if !utf8.ValidRune(r) {
			continue
		}
		scalars++
		key := strconv.Itoa(int(r))
		if value := counts(norm.NFC, r); value != 0 {
			nfc[key] = value
		}
		if value := counts(norm.NFKC, r); value != 0 {
			nfkc[key] = value
		}
		for _, variant := range []struct {
			form norm.Form
			data map[string]any
		}{{norm.NFC, nfcProperties}, {norm.NFKC, nfkcProperties}} {
			p := variant.form.PropertiesString(string(r))
			value := reflect.ValueOf(p)
			ccc := int(value.FieldByName("ccc").Uint())
			back := int((value.FieldByName("flags").Uint() >> 3) & 1)
			packed := counts(variant.form, r)
			decomposition := string(p.Decomposition())
			if r >= 0xac00 && r < 0xd7a4 {
				trail := 2
				if (r-0xac00)%28 == 0 {
					trail = 1
				}
				if ccc != 0 || back != 0 || decomposition != "" || packed != trail {
					panic("locked Hangul algorithm does not match metadata")
				}
				continue
			}
			if ccc != 0 || back != 0 || packed != 0 || decomposition != "" {
				variant.data[key] = []any{ccc, packed / 4, packed % 4, back, decomposition}
			}
		}
		text := string(r)
		if folded := width.Fold.String(text); folded != text {
			if utf8.RuneCountInString(folded) != 1 {
				panic(fmt.Sprintf("width mapping is not single-to-single: %U", r))
			}
			widthSource.WriteRune(r)
			widthTarget.WriteString(folded)
		}
		if unicode.IsSpace(r) {
			spaces.WriteRune(r)
		}
	}
	if scalars != 1112064 || widthSource.Len() == 0 || utf8.RuneCountInString(widthSource.String()) != 226 || utf8.RuneCountInString(spaces.String()) != 25 {
		panic("locked scalar/width/space inventory changed")
	}
	if counts(norm.NFC, 0) != 0 || counts(norm.NFKC, 0) != 0 {
		panic("unexpected NUL stream-safe metadata")
	}
	files := map[string]string{}
	write := func(name, text string) {
		data := []byte(text)
		must(os.WriteFile(filepath.Join(out, name), data, 0600))
		files[name] = digest(data)
	}
	nfcJSON, err := json.Marshal(nfcProperties)
	must(err)
	nfkcJSON, err := json.Marshal(nfkcProperties)
	must(err)
	recompJSON, err := json.Marshal(recomposition)
	must(err)
	write("declare.sql", "-- Generated by sharedpg_unicode_generate.go; Go 1.26.5, x/text v0.34.0, Unicode 15.0.0.\n"+
		"-- Place these declarations in the existing quote function's DECLARE section.\n"+
		"v_width_source CONSTANT text := "+hexText(widthSource.String())+";\n"+
		"v_width_target CONSTANT text := "+hexText(widthTarget.String())+";\n"+
		"v_go_space CONSTANT text := "+hexText(spaces.String())+";\n"+
		"-- [internal CCC,nLead,nTrail,combinesBackward,fully expanded decomposition].\n"+
		"-- Missing scalars have zero metadata; Hangul is checked and derived algorithmically.\n"+
		"v_nfc_properties CONSTANT jsonb := "+sqlJSON(nfcJSON)+";\n"+
		"v_nfkc_properties CONSTANT jsonb := "+sqlJSON(nfkcJSON)+";\n"+
		"v_unicode_recomposition CONSTANT jsonb := "+sqlJSON(recompJSON)+";\n"+
		unicodeLocals)
	for _, form := range []string{"NFC", "NFKC"} {
		write(strings.ToLower(form)+".sql", operation(form))
	}
	write("width.sql", "-- width.Fold before NFC; consumes and replaces v_unicode_input.\nv_unicode_input := translate(v_unicode_input,v_width_source,v_width_target);\n")
	write("space.sql", "-- strings.TrimSpace: btrim(v_unicode_input,v_go_space).\n-- unicode.IsSpace removal: translate(v_unicode_input,v_go_space,'').\n")

	oracle, err := os.Create(filepath.Join(out, "oracle.csv"))
	must(err)
	w := csv.NewWriter(oracle)
	families := map[string]int{}
	add := func(family, id, input string) {
		if strings.ContainsRune(input, 0) {
			panic("PostgreSQL text cannot contain NUL")
		}
		canonical := norm.NFC.String(input)
		compatibility := norm.NFKC.String(input)
		strip := strings.Map(func(r rune) rune {
			if unicode.IsSpace(r) {
				return -1
			}
			return r
		}, compatibility)
		must(w.Write([]string{family, id, hex.EncodeToString([]byte(input)), hex.EncodeToString([]byte(canonical)), hex.EncodeToString([]byte(compatibility)), hex.EncodeToString([]byte(norm.NFC.String(width.Fold.String(input)))), hex.EncodeToString([]byte(strings.TrimSpace(input))), hex.EncodeToString([]byte(strip))}))
		families[family]++
	}
	for r := rune(1); r <= unicode.MaxRune; r++ {
		if !utf8.ValidRune(r) {
			continue
		}
		id := strconv.Itoa(int(r))
		add("scalar", id, string(r))
		if nfc[id] != 0 || nfkc[id] != 0 {
			// Exercise both the rune's leading count and its trailing count;
			// a scalar alone cannot expose the stream-safe boundary.
			for _, prefix := range []int{28, 29, 30} {
				add("scalar_boundary", id+"-"+strconv.Itoa(prefix), "a"+strings.Repeat("\u0301", prefix)+string(r)+strings.Repeat("\u0300", 4))
			}
			add("scalar_trailing", id, string(r)+strings.Repeat("\u0301", 31))
		}
	}
	lines := bufio.NewScanner(strings.NewReader(string(normalizationTest)))
	lineNumber := 0
	for lines.Scan() {
		lineNumber++
		line := strings.TrimSpace(strings.SplitN(lines.Text(), "#", 2)[0])
		if line == "" || strings.HasPrefix(line, "@") {
			continue
		}
		fields := strings.Split(line, ";")
		if len(fields) < 5 {
			panic("invalid Unicode normalization test line")
		}
		values := make([]string, 5)
		for i := range values {
			var value strings.Builder
			for _, scalar := range strings.Fields(fields[i]) {
				number, err := strconv.ParseUint(scalar, 16, 32)
				must(err)
				if !utf8.ValidRune(rune(number)) || number == 0 {
					panic("invalid Unicode normalization test scalar")
				}
				value.WriteRune(rune(number))
			}
			values[i] = value.String()
		}
		for i, value := range values {
			wantNFC := values[1]
			if i >= 3 {
				wantNFC = values[3]
			}
			if norm.NFC.String(value) != wantNFC || norm.NFKC.String(value) != values[3] {
				panic(fmt.Sprintf("Go disagrees with official normalization test line %d column %d", lineNumber, i+1))
			}
			add("normalization15", strconv.Itoa(lineNumber)+"-"+strconv.Itoa(i+1), value)
		}
	}
	must(lines.Err())
	for _, token := range []string{"\u0301", "\u0315\u0300", "\u0f73", "\u0344", "\u1161", "\u11a8", "\uff9e", "\uff9f", "\u3099", "\u1d165", "\u1f82"} {
		for _, size := range []int{0, 1, 14, 15, 16, 28, 29, 30, 31, 32, 60, 61, 120} {
			for _, starter := range []string{"", "a", "\u1100", "\uac00", "\uff76", "\u00e1"} {
				id := hex.EncodeToString([]byte(starter+token)) + "-" + strconv.Itoa(size)
				add("mixed_boundary", id, starter+strings.Repeat(token, size))
			}
		}
	}
	for _, value := range []string{spaces.String() + "Ａ\u0301" + spaces.String(), "a" + strings.Repeat("\u0315\u0300", 20), "\u1100" + strings.Repeat("\u1161\u11a8", 31), "ｶﾞ", "𝐀ＡA"} {
		add("mixed_boundary", hex.EncodeToString([]byte(value)), value)
	}
	// Exercise every actual packed composition key in every scalar plane. The
	// uint16-key aliases are observable native behavior, even for unassigned
	// scalars; standard PostgreSQL normalize cannot reproduce them.
	keys := make([]string, 0, len(recomposition))
	for key := range recomposition {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	for _, key := range keys {
		packed, err := strconv.ParseUint(key, 10, 32)
		must(err)
		for rightPlane := 0; rightPlane <= 16; rightPlane++ {
			right := rune(packed&65535) + rune(rightPlane*65536)
			if !utf8.ValidRune(right) || right == 0 {
				continue
			}
			backward := false
			for _, form := range []norm.Form{norm.NFC, norm.NFKC} {
				p := reflect.ValueOf(form.PropertiesString(string(right)))
				backward = backward || p.FieldByName("flags").Uint()&8 != 0
			}
			if rightPlane != 0 && !backward {
				continue
			}
			for leftPlane := 0; leftPlane <= 16; leftPlane++ {
				left := rune(packed>>16) + rune(leftPlane*65536)
				if !utf8.ValidRune(left) || left == 0 {
					continue
				}
				id := key + "-" + strconv.Itoa(leftPlane) + "-" + strconv.Itoa(rightPlane)
				add("composition_alias", id, string(left)+string(right))
				add("composition_blocked", id, string(left)+"\u0315"+string(right))
				add("composition_unblocked", id, string(left)+"\u0334"+string(right))
			}
		}
	}
	w.Flush()
	must(w.Error())
	must(oracle.Close())
	data, err := os.ReadFile(filepath.Join(out, "oracle.csv"))
	must(err)
	files["oracle.csv"] = digest(data)
	manifest, err := json.MarshalIndent(map[string]any{"generator": "sharedpg_unicode_generate.go", "generator_sha256": digest(sourceBytes), "go": runtime.Version(), "x_text": "v0.34.0", "norm_unicode": norm.Version, "width_unicode": width.UnicodeVersion, "go_unicode": unicode.Version, "authority_sources": authority, "normalization_test_sha256": normalizationTestSHA, "scalar_metadata_count": scalars, "pg_scalar_count": scalars - 1, "pg_nul": "excluded: PostgreSQL text rejects U+0000; its zero metadata is checked by generation", "nfc_nonzero_count": len(nfc), "nfkc_nonzero_count": len(nfkc), "nfc_property_count": len(nfcProperties), "nfkc_property_count": len(nfkcProperties), "recomposition_count": len(recomposition), "width_map_count": 226, "space_count": 25, "oracle_families": families, "files": files}, "", "  ")
	must(err)
	write("manifest.json", string(manifest)+"\n")
	fmt.Printf("generated scalars=%d NFC-metadata=%d NFKC-metadata=%d families=%v\n", scalars, len(nfc), len(nfkc), families)
}

func assertAuthority() {
	if runtime.Version() != "go1.26.5" || norm.Version != "15.0.0" || width.UnicodeVersion != "15.0.0" || unicode.Version != "15.0.0" {
		panic("locked Go/Unicode authority changed")
	}
	build, ok := debug.ReadBuildInfo()
	if !ok {
		panic("Go dependency build info unavailable")
	}
	found := false
	for _, dependency := range build.Deps {
		if dependency.Path == "golang.org/x/text" {
			found = dependency.Version == "v0.34.0" && dependency.Replace == nil
		}
	}
	if !found {
		panic("expected unreplaced golang.org/x/text v0.34.0")
	}
	t := reflect.TypeOf(norm.NFC.PropertiesString("a"))
	names := []string{"pos", "size", "ccc", "tccc", "nLead", "flags", "index"}
	if t.PkgPath() != "golang.org/x/text/unicode/norm" || t.Name() != "Properties" || t.Size() != 8 || t.NumField() != len(names) {
		panic("norm.Properties shape changed")
	}
	for i, name := range names {
		field := t.Field(i)
		kind, offset := reflect.Uint8, uintptr(i)
		if i == 6 {
			kind = reflect.Uint16
		}
		if field.Name != name || field.Type.Kind() != kind || field.Offset != offset {
			panic("norm.Properties field shape changed: " + name)
		}
		if name == "flags" && (field.Type.Name() != "qcInfo" || field.Type.PkgPath() != t.PkgPath()) {
			panic("norm.Properties flags type changed")
		}
	}
}

func counts(form norm.Form, r rune) int {
	p := reflect.ValueOf(form.PropertiesString(string(r)))
	lead := int(p.FieldByName("nLead").Uint())
	trail := int(p.FieldByName("flags").Uint() & 3)
	if lead > 3 || trail > 3 || (lead != 0 && lead != trail) {
		panic(fmt.Sprintf("invalid locked stream-safe properties for %U", r))
	}
	return lead*4 + trail
}

func operation(form string) string {
	properties := "v_" + strings.ToLower(form) + "_properties"
	return "-- Quote-only " + form + ": input v_unicode_input; output v_unicode_output.\n" +
		"-- Locked Go raw stream-safe accounting, segment decomposition, ordering and composition.\n" + `v_unicode_output := '';
v_unicode_count := 0;
v_unicode_size := 0;
v_unicode_runes := ARRAY[]::integer[];
v_unicode_cccs := ARRAY[]::integer[];
v_unicode_backwards := ARRAY[]::boolean[];
FOR v_unicode_index IN 1..char_length(v_unicode_input) LOOP
  v_unicode_scalar := ascii(substr(v_unicode_input,v_unicode_index,1));
  v_unicode_property := coalesce(` + properties + `->v_unicode_scalar::text,'[0,0,0,0,""]'::jsonb);
  v_unicode_lead := (v_unicode_property->>1)::integer;
  v_unicode_trail := (v_unicode_property->>2)::integer;
  IF v_unicode_scalar>=44032 AND v_unicode_scalar<55204 THEN
    v_unicode_trail := CASE WHEN (v_unicode_scalar-44032)%28=0 THEN 1 ELSE 2 END;
  END IF;
  IF v_unicode_count+v_unicode_lead>30 THEN
    -- Overflow consumes no input rune: append CGJ, flush, and then insert this rune.
    v_unicode_size := v_unicode_size+1;
    v_unicode_runes[v_unicode_size] := 847;
    v_unicode_cccs[v_unicode_size] := 0;
    v_unicode_backwards[v_unicode_size] := false;
` + flushSegment() + `    v_unicode_count := 0;
  END IF;
  IF v_unicode_lead=0 THEN
` + flushSegment() + `    v_unicode_count := v_unicode_trail;
  ELSE
    v_unicode_count := v_unicode_count+v_unicode_lead;
  END IF;
  IF v_unicode_scalar>=44032 AND v_unicode_scalar<55204 THEN
    -- composition.go decomposeHangul appends components with zero Properties.
    v_unicode_hangul := v_unicode_scalar-44032;
    v_unicode_decomposition := chr(4352+v_unicode_hangul/588)||chr(4449+(v_unicode_hangul/28)%21);
    IF v_unicode_hangul%28<>0 THEN
      v_unicode_decomposition := v_unicode_decomposition||chr(4519+v_unicode_hangul%28);
    END IF;
    FOR v_unicode_part_index IN 1..char_length(v_unicode_decomposition) LOOP
      v_unicode_size := v_unicode_size+1;
      v_unicode_runes[v_unicode_size] := ascii(substr(v_unicode_decomposition,v_unicode_part_index,1));
      v_unicode_cccs[v_unicode_size] := 0;
      v_unicode_backwards[v_unicode_size] := false;
    END LOOP;
  ELSE
    v_unicode_decomposition := v_unicode_property->>4;
    v_unicode_has_decomposition := v_unicode_decomposition<>'';
    IF NOT v_unicode_has_decomposition THEN
      v_unicode_decomposition := chr(v_unicode_scalar);
    END IF;
    FOR v_unicode_part_index IN 1..char_length(v_unicode_decomposition) LOOP
      v_unicode_part := ascii(substr(v_unicode_decomposition,v_unicode_part_index,1));
      v_unicode_part_property := coalesce(` + properties + `->v_unicode_part::text,'[0,0,0,0,""]'::jsonb);
      v_unicode_ccc := (v_unicode_part_property->>0)::integer;
      v_unicode_backward := (v_unicode_part_property->>3)::integer<>0;
      IF v_unicode_has_decomposition AND v_unicode_ccc=0 AND NOT v_unicode_backward THEN
        -- insertDecomposed flushes at BoundaryBefore without resetting streamSafe.
` + flushSegment() + `      END IF;
      v_unicode_position := v_unicode_size+1;
      IF v_unicode_ccc>0 THEN
        WHILE v_unicode_position>1 AND v_unicode_cccs[v_unicode_position-1]>v_unicode_ccc LOOP
          v_unicode_position := v_unicode_position-1;
        END LOOP;
      END IF;
      FOR v_unicode_j IN REVERSE v_unicode_size..v_unicode_position LOOP
        v_unicode_runes[v_unicode_j+1] := v_unicode_runes[v_unicode_j];
        v_unicode_cccs[v_unicode_j+1] := v_unicode_cccs[v_unicode_j];
        v_unicode_backwards[v_unicode_j+1] := v_unicode_backwards[v_unicode_j];
      END LOOP;
      v_unicode_size := v_unicode_size+1;
      v_unicode_runes[v_unicode_position] := v_unicode_part;
      v_unicode_cccs[v_unicode_position] := v_unicode_ccc;
      v_unicode_backwards[v_unicode_position] := v_unicode_backward;
    END LOOP;
  END IF;
END LOOP;
` + flushSegment()
}

