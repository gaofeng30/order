//go:build ignore

// Generate the Unicode constants and inline operations used by the shared-PG
// quote function. Run with Go 1.26.5 from this repository:
//
//	go run services/api/internal/quote/sharedpg_unicode_generate.go OUTSIDE_REPO_DIR NormalizationTest-15.0.0.txt
//
// This program never edits quote.sql. Its output must pass the real PostgreSQL
// conformance probe before being copied into that function. Reflection is only
// used here, under exact version and field-shape guards; runtime code uses no
// reflection or additional SQL function.
package main

