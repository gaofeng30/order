// This block is intentionally inlined at each of Go's segment-flush points.
// It creates no SQL helper function and preserves assignRune's zero metadata.
func flushSegment() string {
	return `    IF v_unicode_size>0 THEN
      v_unicode_k := 2;
      v_unicode_starter := 1;
      v_unicode_hangul_mode := false;
      FOR v_unicode_i IN 2..v_unicode_size LOOP
        IF v_unicode_runes[v_unicode_i]>=4352 AND v_unicode_runes[v_unicode_i]<4608 THEN
          -- Go isJamoVT recognizes the complete U+1100..U+11FF byte range.
          v_unicode_hangul_mode := true;
        END IF;
        v_unicode_combined := 0;
        IF v_unicode_hangul_mode OR v_unicode_backwards[v_unicode_i] THEN
          v_unicode_ccc_b := v_unicode_cccs[v_unicode_k-1];
          v_unicode_ccc_c := v_unicode_cccs[v_unicode_i];
          v_unicode_blocked := false;
          IF v_unicode_ccc_b=0 THEN
            v_unicode_starter := v_unicode_k-1;
          ELSE
            v_unicode_blocked := v_unicode_starter<>v_unicode_k-1 AND v_unicode_ccc_b>=v_unicode_ccc_c;
          END IF;
          IF NOT v_unicode_blocked THEN
            v_unicode_l := v_unicode_runes[v_unicode_starter];
            v_unicode_v := v_unicode_runes[v_unicode_i];
            IF v_unicode_hangul_mode THEN
              IF v_unicode_l>=4352 AND v_unicode_l<4371 AND v_unicode_v>=4449 AND v_unicode_v<4470 THEN
                v_unicode_combined := 44032+(v_unicode_l-4352)*588+(v_unicode_v-4449)*28;
              ELSIF v_unicode_l>=44032 AND v_unicode_l<55204 AND v_unicode_v>4519 AND v_unicode_v<4547 AND (v_unicode_l-44032)%28=0 THEN
                v_unicode_combined := v_unicode_l+v_unicode_v-4519;
              END IF;
            ELSE
              -- formInfo.go combine uses uint16 components, including its astral aliases.
              v_unicode_key := (v_unicode_l%65536)::bigint*65536+(v_unicode_v%65536);
              v_unicode_combined := coalesce((v_unicode_recomposition->>v_unicode_key::text)::integer,0);
            END IF;
          END IF;
        END IF;
        IF v_unicode_combined<>0 THEN
          v_unicode_runes[v_unicode_starter] := v_unicode_combined;
          v_unicode_cccs[v_unicode_starter] := 0;
          v_unicode_backwards[v_unicode_starter] := false;
        ELSE
          v_unicode_runes[v_unicode_k] := v_unicode_runes[v_unicode_i];
          v_unicode_cccs[v_unicode_k] := v_unicode_cccs[v_unicode_i];
          v_unicode_backwards[v_unicode_k] := v_unicode_backwards[v_unicode_i];
          v_unicode_k := v_unicode_k+1;
        END IF;
      END LOOP;
      FOR v_unicode_j IN 1..v_unicode_k-1 LOOP
        v_unicode_output := v_unicode_output||chr(v_unicode_runes[v_unicode_j]);
      END LOOP;
      v_unicode_size := 0;
      v_unicode_runes := ARRAY[]::integer[];
      v_unicode_cccs := ARRAY[]::integer[];
      v_unicode_backwards := ARRAY[]::boolean[];
    END IF;
`
}

func readRecomposition() (map[string]uint32, map[string]string) {
	command := exec.Command("go", "env", "GOMODCACHE")
	command.Env = append(os.Environ(), "GOPROXY=off", "GOTOOLCHAIN=go1.26.5")
	cache, err := command.Output()
	must(err)
	directory := filepath.Join(strings.TrimSpace(string(cache)), "golang.org/x/text@v0.34.0/unicode/norm")
	locked := map[string]string{
		"tables15.0.0.go": "49dda94f9429bac8c29efe11e09558d46abfaa3c8e1de59816f2910b99cade04",
		"composition.go":  "3d1be52960f2693926472819b747646e7d2371d2bb5f53097cf9d46c913052df",
		"forminfo.go":     "fceb28bef5efec8347536a89018e906f607a70a91051d9360b3656867efe2d9e",
		"normalize.go":    "b9e7aeff51e6cb036ff4e8c6255410e7068c112e329a137d333e639f63c4a8ab",
	}
	var table []byte
	for name, expected := range locked {
		data, err := os.ReadFile(filepath.Join(directory, name))
		must(err)
		if digest(data) != expected {
			panic("locked normalization source hash changed: " + name)
		}
		if name == "tables15.0.0.go" {
			table = data
		}
	}
	if !strings.Contains(string(table), "//go:build !go1.27") {
		panic("effective normalization table build tag changed")
	}
	file, err := parser.ParseFile(token.NewFileSet(), "tables15.0.0.go", table, 0)
	must(err)
	var packed string
	definitions := 0
	for _, declaration := range file.Decls {
		general, ok := declaration.(*ast.GenDecl)
		if !ok || general.Tok != token.CONST {
			continue
		}
		for _, specification := range general.Specs {
			value := specification.(*ast.ValueSpec)
			for i, name := range value.Names {
				if name.Name == "recompMapPacked" {
					definitions++
					packed = stringConstant(value.Values[i])
				}
			}
		}
	}
	if definitions != 1 || len(packed) != 7528 || len(packed)%8 != 0 {
		panic("locked recomposition table shape changed")
	}
	result := map[string]uint32{}
	for i := 0; i < len(packed); i += 8 {
		key := binary.BigEndian.Uint32([]byte(packed[i : i+4]))
		value := binary.BigEndian.Uint32([]byte(packed[i+4 : i+8]))
		name := strconv.FormatUint(uint64(key), 10)
		if _, found := result[name]; found || value == 0 || !utf8.ValidRune(rune(value)) {
			panic("invalid or duplicate locked recomposition entry")
		}
		result[name] = value
	}
	return result, locked
}

func stringConstant(expression ast.Expr) string {
	switch value := expression.(type) {
	case *ast.BasicLit:
		if value.Kind != token.STRING {
			panic("expected literal recomposition string")
		}
		text, err := strconv.Unquote(value.Value)
		must(err)
		return text
	case *ast.BinaryExpr:
		if value.Op != token.ADD {
			panic("expected concatenated recomposition string")
		}
		return stringConstant(value.X) + stringConstant(value.Y)
	case *ast.ParenExpr:
		return stringConstant(value.X)
	default:
		panic("unsupported recomposition constant expression")
	}
}

func sqlJSON(data []byte) string {
	return "'" + strings.ReplaceAll(string(data), "'", "''") + "'::jsonb"
}

func hexText(value string) string {
	return "convert_from(decode('" + hex.EncodeToString([]byte(value)) + "','hex'),'UTF8')"
}

func digest(value []byte) string {
	return fmt.Sprintf("%x", sha256.Sum256(value))
}

func must(err error) {
	if err != nil {
		panic(err)
	}
}
